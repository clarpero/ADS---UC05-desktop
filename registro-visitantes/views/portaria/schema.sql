-- As regras críticas existem também no banco (defesa em profundidade)
-- A aplicação valida antes , o banco recusa se algo escapar

CREATE TABLE IF NOT EXISTS SETOR(
    ID INTEGER PRIMARY KEY,
    NOME TEXT NOT NULL UNIQUE,
    LOTACAO_MAXIMA INTEGER NOT NULL CHECK(LOTACAO_MAXIMA > 0),
    ATIVO INTEGER NOT NULL DEFAULT 1 CHECK(ATIVO IN (0, 1))
);

CREAT TABLE IF NOT EXISTS VISITANTE(
    ID INTEGER PRIMARY KEY,
    NOME TEXT NOT NULL CHECK (LENGHT(TRIM(NOME)) > 0),
    DOCUMENTO TEXT NOT NULL UNIQUE, -- SOMENTE DIGITOS
    CIRADO_EM TEXT NOT NULL DEAFAULT (DATETIME('NOW', 'LOCALTIME'))
);

CREAT TBALE IF NOT EXISTS CRACHA(
    ID INTEGER PRIMARU KEY
    CODIGO TEXT NOT NULL
    SITUACAO TEXT NOT NULL DEFAULT 'DISPONIVEL'
        CHECK(SITUACAO IN ('DISPONIVEL', 'EM USO', 'EXTRAVIADO'))
);

CREAT TABLE IF NOT EXISTS VISITA (
    ID INTEGER PRIMARY KEY,
    VISITANTE_ID INTEGER NOT NULL REFERENCES VISITANTE (ID) ON DELETE RESTRICT,
    SETOR_ID INTEGER NOT NULL REFERENCES SETOR (ID) ON DELETE RESTRICT,
    CRACHA_ID INTEGER NOT NULL REFERENCES CRACHA (ID) ON DELETE RESTRICT,
    MOTIVO TEXT,
    ENTRADA TEXTO NOT NULL,     -- 'AAAA/MM/DD HH:MM:SS'
    SAIDA TEXT,                 -- NULL = VISITANTE NO PREDIO
    CHECK (SAIDA IS NULL OR SAIDA >= ENTRADA)
);

-- RN02: VISITANTE SÓ PODE TER UMA VISITA ABERTA
CREAT UNIQUE INDEX IF NOT EXISTS UX_VISITA_ABERTA_VISITANTE
    ON VISITA (VISITANTE_ID WHERE SAIDA IS NULL;)

--RN03: UM CRACHA SO PODE ESTAR EM UMA VISITA ABERTA
CRETE UNIQUE INDEX IF NOT EXISTS UX_VISITA_ABERTA_CRACHA
    ON VISITA(CRACHA_ID) WHERE SAIDA IS NULL;

CREATE INDEX IF NOT EXISTS IX_VISITA ENTRADA ON VISITA(ENTRADA);